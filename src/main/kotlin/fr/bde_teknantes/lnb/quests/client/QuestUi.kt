package fr.bde_teknantes.lnb.quests.client

import fr.bde_teknantes.lnb.quests.LnbQuests
import net.minecraft.client.gui.Font
import net.minecraft.client.gui.GuiGraphics
import net.minecraft.core.registries.BuiltInRegistries
import net.minecraft.network.chat.Component
import net.minecraft.network.chat.MutableComponent
import net.minecraft.resources.ResourceLocation
import net.minecraft.world.item.ItemStack
import net.minecraft.world.item.Items
import java.text.NumberFormat
import java.util.Locale

/**
 * The quest screens' look: LNB Economy's casino kit (green felt, gold frames, crimson actions), copied into this mod so
 * it stands alone, plus round quest nodes whose level shows as pics on the ring. Sprites live in
 * `textures/gui/sprites/`; they are generated by `visual-previews/scripts/gen_sprites.py`.
 */
object QuestUi {
    private fun sprite(name: String) = ResourceLocation.fromNamespaceAndPath(LnbQuests.ID, name)

    val PANEL = sprite("panel")
    val PANEL_INSET = sprite("panel_inset")
    val SLOT = sprite("slot")
    val TEXT_FIELD = sprite("text_field")
    val PLAQUE_SIDE = sprite("plaque_side")
    val SECRET = sprite("node/secret")
    val BRACKET_SIDE_TOP = sprite("bracket_side_top")
    val BRACKET_SIDE_BOTTOM = sprite("bracket_side_bottom")
    val FLASH_CLASP = sprite("flash_clasp")
    val BADGE_CHECK = sprite("badge_check")
    val BADGE_READY = sprite("badge_ready")
    val BADGE_LOCK = sprite("badge_lock")

    class ButtonSprites(name: String) {
        private val normal = sprite(name)
        private val highlighted = sprite("${name}_highlighted")
        private val disabled = sprite("${name}_disabled")

        fun get(active: Boolean, hovered: Boolean) = when {
            !active -> disabled
            hovered -> highlighted
            else -> normal
        }
    }

    val PRIMARY = ButtonSprites("button")
    val SECONDARY = ButtonSprites("button_secondary")

    const val GOLD_TEXT = 0xFFFFD45A.toInt()
    const val IVORY = 0xFFF0E8D0.toInt()
    const val DIM = 0xFFB0BEAC.toInt()
    const val MUTED = 0xFF788A7C.toInt()
    const val GREEN = 0xFF6EE682.toInt()
    const val TITLE_OUTLINE = 0xFF140E06.toInt()
    const val GOLD_LT = 0xFFE8CA84.toInt()
    const val GOLD_MD = 0xFFB6904C.toInt()
    const val GOLD_DK = 0xFF6E4C22.toInt()
    const val GOLD_HI = 0xFFFAEABA.toInt()
    const val FELT_DEEP = 0xFF102A20.toInt()
    const val OUTLINE = 0xFF0C1813.toInt()
    const val LOCKED_LINK = 0xFF34463C.toInt()
    const val GRID = 0xFF224A38.toInt()

    /** The LNBit coin, from this mod's own font. */
    private val COIN_FONT = ResourceLocation.fromNamespaceAndPath(LnbQuests.ID, "icons")

    fun coin(): MutableComponent = Component.literal("Ⓛ").withStyle { it.withFont(COIN_FONT).withColor(0xFFFFFF) }

    /** "Ⓛ 1 165", the coin then the amount. */
    fun amount(value: Long, language: String, approx: Boolean = false): MutableComponent =
        Component.empty().append(if (approx) Component.literal("≈ ") else Component.empty()).append(coin()).append(" " + number(value, language))

    fun number(value: Long, language: String): String =
        NumberFormat.getIntegerInstance(if (language.startsWith("fr")) Locale.FRANCE else Locale.UK).format(value)

    fun stack(id: String?): ItemStack {
        val item = id?.let(ResourceLocation::tryParse)?.let { BuiltInRegistries.ITEM.getOptional(it).orElse(null) }
        return ItemStack(item ?: Items.PAPER)
    }

    /** A window or chapter title: gold letters ringed with a dark outline. */
    fun title(graphics: GuiGraphics, font: Font, text: Component, x: Int, y: Int) {
        font.drawInBatch8xOutline(
            text.visualOrderText, x.toFloat(), y.toFloat(), GOLD_TEXT, TITLE_OUTLINE,
            graphics.pose().last().pose(), graphics.bufferSource(), 0xF000F0,
        )
        graphics.flush()
    }

    fun fit(font: Font, text: String, width: Int): String =
        if (font.width(text) <= width) text else font.plainSubstrByWidth(text, maxOf(0, width - font.width("..."))) + "..."

    // Quest nodes.

    enum class NodeState(val key: String) { CLAIMED("claimed"), READY("ready"), PROGRESS("progress"), LOCKED("locked") }

    /** The frame sprites are 32 px square around a 24 px ring; the glow is 36 px. */
    const val NODE = 32
    const val RING = 24

    /**
     * A round quest node centered on ([x], [y]): its frame for [state] and [level] (1 to 3: none, 4 or 8 pics), the
     * item, a corner badge, and the gold glow of a quest to claim when [glow].
     */
    fun node(graphics: GuiGraphics, x: Int, y: Int, icon: ItemStack, state: NodeState, level: Int, glow: Boolean = true) {
        val lvl = level.coerceIn(1, 3)
        if (state == NodeState.READY && glow) {
            graphics.blitSprite(sprite("node/glow_$lvl"), x - NODE / 2 - 2, y - NODE / 2 - 2, NODE + 4, NODE + 4)
        }
        graphics.blitSprite(sprite("node/frame_${state.key}_$lvl"), x - NODE / 2, y - NODE / 2, NODE, NODE)
        if (state == NodeState.LOCKED) {
            graphics.setColor(0.45f, 0.5f, 0.47f, 1f)
            graphics.renderFakeItem(icon, x - 8, y - 8)
            graphics.setColor(1f, 1f, 1f, 1f)
        } else {
            graphics.renderFakeItem(icon, x - 8, y - 8)
        }
        val badge = when (state) {
            NodeState.CLAIMED -> BADGE_CHECK
            NodeState.READY -> BADGE_READY
            NodeState.LOCKED -> BADGE_LOCK
            NodeState.PROGRESS -> null
        }
        if (badge != null) {
            graphics.pose().pushPose()
            graphics.pose().translate(0f, 0f, 200f) // over the item
            graphics.blitSprite(badge, x + (RING / 2 * 0.7).toInt() - 3, y - (RING / 2 * 0.7).toInt() - 5, 8, 8)
            graphics.pose().popPose()
        }
    }

    /** A dependency link between two nodes on the same row, FTB style, with a dark outline. */
    fun link(graphics: GuiGraphics, x0: Int, x1: Int, y: Int, color: Int) {
        graphics.fill(x0, y - 2, x1, y + 2, OUTLINE)
        graphics.fill(x0, y - 1, x1, y + 1, color)
    }

    /** A thin progress bar: dark felt with a gold fill. */
    fun bar(graphics: GuiGraphics, x: Int, y: Int, width: Int, height: Int, fraction: Double, fill: Int = GOLD_LT) {
        graphics.fill(x, y, x + width, y + height, FELT_DEEP)
        val w = (width * fraction.coerceIn(0.0, 1.0)).toInt()
        if (w > 0) graphics.fill(x, y, x + w, y + height, fill)
    }

    /** A kit button drawn by hand: its sprite and a centered label. */
    fun button(graphics: GuiGraphics, font: Font, sprites: ButtonSprites, x: Int, y: Int, w: Int, h: Int, label: Component, active: Boolean, hovered: Boolean) {
        graphics.blitSprite(sprites.get(active, hovered), x, y, w, h)
        graphics.drawString(font, label, x + (w - font.width(label)) / 2, y + (h - 8) / 2, if (active) IVORY else MUTED, true)
    }
}
